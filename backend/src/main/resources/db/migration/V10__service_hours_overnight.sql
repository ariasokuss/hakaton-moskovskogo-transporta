-- Часы работы маршрутов (V3 записал у шести маршрутов «0–23», и интерфейс показывал «работает с 0:00 до 23:59»).
-- Ни один маршрут не работает круглосуточно: по посадкам сен–окт 2025 (data/load/load_hourly.csv, доля часа в суточном
-- объёме) в часы 2–3 посадок 0%, первые пассажиры — в 5 ч (0.1–0.9%), последние рейсы у 7, 11, 12, 17, 26, 50 — после
-- полуночи (час 0: 0.12–0.31%). Окно «5:00 — 00:59» переходит через полночь: service_hour_end < service_hour_start
-- означает последний час работы уже следующих суток. Порог — 0.1% суточного объёма, как в V3.
UPDATE core.route SET service_hour_start = 5, service_hour_end = 0  WHERE route_id IN (7, 11, 12, 17, 26, 50);
UPDATE core.route SET service_hour_start = 5, service_hour_end = 23 WHERE route_id IN (1, 25, 28);
COMMENT ON COLUMN core.route.service_hour_end IS
    'последний час с пассажирами (доля > 0.1% суточного объёма); меньше service_hour_start — окно переходит через полночь';
